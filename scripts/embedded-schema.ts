import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

// Regenerates the SQL the embedded (no DATABASE_URL) database is created from. Run after editing schema.prisma.
const sql = execSync("npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script", { encoding: "utf8" });
writeFileSync(
  "src/lib/embedded-schema.ts",
  `// Generated by scripts/embedded-schema.ts from prisma/schema.prisma. Do not edit.\nexport const EMBEDDED_SCHEMA_SQL = ${JSON.stringify(sql)};\n`,
);
console.log("Wrote src/lib/embedded-schema.ts");
